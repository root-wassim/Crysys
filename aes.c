static const uint8_t rcon[11] = {0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36};

static uint8_t xtime(uint8_t a) { return (a & 0x80) ? ((a << 1) ^ 0x1b) : (a << 1); }
static uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        b >>= 1;
        a = xtime(a);
    }
    return p;
}

static void key_expansion(const uint8_t *key, uint8_t *rk, int nk, int nr) {
    int i = 0;
    while (i < nk) { rk[i*4]=key[i*4]; rk[i*4+1]=key[i*4+1]; rk[i*4+2]=key[i*4+2]; rk[i*4+3]=key[i*4+3]; i++; }
    while (i < 4*(nr+1)) {
        uint8_t tmp[4] = {rk[(i-1)*4],rk[(i-1)*4+1],rk[(i-1)*4+2],rk[(i-1)*4+3]};
        if (i % nk == 0) {
            uint8_t t = tmp[0]; tmp[0]=sbox[tmp[1]]^rcon[i/nk]; tmp[1]=sbox[tmp[2]]; tmp[2]=sbox[tmp[3]]; tmp[3]=sbox[t];
        } else if (nk > 6 && i % nk == 4) {
            tmp[0]=sbox[tmp[0]]; tmp[1]=sbox[tmp[1]]; tmp[2]=sbox[tmp[2]]; tmp[3]=sbox[tmp[3]];
        }
        rk[i*4]  =rk[(i-nk)*4]  ^tmp[0]; rk[i*4+1]=rk[(i-nk)*4+1]^tmp[1];
        rk[i*4+2]=rk[(i-nk)*4+2]^tmp[2]; rk[i*4+3]=rk[(i-nk)*4+3]^tmp[3];
        i++;
    }
}

static void add_round_key(uint8_t state[4][4], const uint8_t *rk) {
    for (int c = 0; c < 4; c++)
        for (int r = 0; r < 4; r++)
            state[r][c] ^= rk[c*4+r];
}

static void sub_bytes(uint8_t state[4][4]) {
    for (int r = 0; r < 4; r++) for (int c = 0; c < 4; c++) state[r][c] = sbox[state[r][c]];
}

static void inv_sub_bytes(uint8_t state[4][4]) {
    for (int r = 0; r < 4; r++) for (int c = 0; c < 4; c++) state[r][c] = inv_sbox[state[r][c]];
}

static void shift_rows(uint8_t state[4][4]) {
    uint8_t tmp;
    tmp=state[1][0]; state[1][0]=state[1][1]; state[1][1]=state[1][2]; state[1][2]=state[1][3]; state[1][3]=tmp;
    tmp=state[2][0]; state[2][0]=state[2][2]; state[2][2]=tmp; tmp=state[2][1]; state[2][1]=state[2][3]; state[2][3]=tmp;
    tmp=state[3][3]; state[3][3]=state[3][2]; state[3][2]=state[3][1]; state[3][1]=state[3][0]; state[3][0]=tmp;
}

static void inv_shift_rows(uint8_t state[4][4]) {
    uint8_t tmp;
    tmp=state[1][3]; state[1][3]=state[1][2]; state[1][2]=state[1][1]; state[1][1]=state[1][0]; state[1][0]=tmp;
    tmp=state[2][0]; state[2][0]=state[2][2]; state[2][2]=tmp; tmp=state[2][1]; state[2][1]=state[2][3]; state[2][3]=tmp;
    tmp=state[3][0]; state[3][0]=state[3][1]; state[3][1]=state[3][2]; state[3][2]=state[3][3]; state[3][3]=tmp;
}

static void mix_columns(uint8_t state[4][4]) {
    for (int c = 0; c < 4; c++) {
        uint8_t s0=state[0][c],s1=state[1][c],s2=state[2][c],s3=state[3][c];
        state[0][c]=gmul(s0,2)^gmul(s1,3)^s2^s3;
        state[1][c]=s0^gmul(s1,2)^gmul(s2,3)^s3;
        state[2][c]=s0^s1^gmul(s2,2)^gmul(s3,3);
        state[3][c]=gmul(s0,3)^s1^s2^gmul(s3,2);
    }
}

static void inv_mix_columns(uint8_t state[4][4]) {
    for (int c = 0; c < 4; c++) {
        uint8_t s0=state[0][c],s1=state[1][c],s2=state[2][c],s3=state[3][c];
        state[0][c]=gmul(s0,0x0e)^gmul(s1,0x0b)^gmul(s2,0x0d)^gmul(s3,0x09);
        state[1][c]=gmul(s0,0x09)^gmul(s1,0x0e)^gmul(s2,0x0b)^gmul(s3,0x0d);
        state[2][c]=gmul(s0,0x0d)^gmul(s1,0x09)^gmul(s2,0x0e)^gmul(s3,0x0b);
        state[3][c]=gmul(s0,0x0b)^gmul(s1,0x0d)^gmul(s2,0x09)^gmul(s3,0x0e);
    }
}

void aes_encrypt_block(const uint8_t in[16], uint8_t out[16], const uint8_t *key, int key_bits) {
    int nk = key_bits / 32;
    int nr = nk + 6;
    uint8_t rk[240];
    key_expansion(key, rk, nk, nr);
    uint8_t state[4][4];
    for (int c = 0; c < 4; c++) for (int r = 0; r < 4; r++) state[r][c] = in[c*4+r];
    add_round_key(state, rk);
    for (int rnd = 1; rnd < nr; rnd++) {
        sub_bytes(state); shift_rows(state); mix_columns(state); add_round_key(state, rk + rnd*16);
    }
    sub_bytes(state); shift_rows(state); add_round_key(state, rk + nr*16);
    for (int c = 0; c < 4; c++) for (int r = 0; r < 4; r++) out[c*4+r] = state[r][c];
}

void aes_decrypt_block(const uint8_t in[16], uint8_t out[16], const uint8_t *key, int key_bits) {
    int nk = key_bits / 32;
    int nr = nk + 6;
    uint8_t rk[240];
    key_expansion(key, rk, nk, nr);
    uint8_t state[4][4];
    for (int c = 0; c < 4; c++) for (int r = 0; r < 4; r++) state[r][c] = in[c*4+r];
    add_round_key(state, rk + nr*16);
    for (int rnd = nr - 1; rnd >= 1; rnd--) {
        inv_shift_rows(state); inv_sub_bytes(state); add_round_key(state, rk + rnd*16); inv_mix_columns(state);
    }
    inv_shift_rows(state); inv_sub_bytes(state); add_round_key(state, rk);
    for (int c = 0; c < 4; c++) for (int r = 0; r < 4; r++) out[c*4+r] = state[r][c];
}

int aes_encrypt_file(const char *infile, const char *outfile, const uint8_t *key, int key_bits) {
    FILE *fin = fopen(infile, "rb");
    if (!fin) return -1;
    FILE *fout = fopen(outfile, "wb");
    if (!fout) { fclose(fin); return -1; }
    uint8_t in_block[16], out_block[16];
    size_t n;
    while ((n = fread(in_block, 1, 16, fin)) > 0) {
        if (n < 16) { uint8_t pad = (uint8_t)(16 - n); for (size_t i = n; i < 16; i++) in_block[i] = pad; }
        aes_encrypt_block(in_block, out_block, key, key_bits);
        fwrite(out_block, 1, 16, fout);
    }
    fclose(fin); fclose(fout);
    return 0;
}

int aes_decrypt_file(const char *infile, const char *outfile, const uint8_t *key, int key_bits) {
    FILE *fin = fopen(infile, "rb");
    if (!fin) return -1;
    FILE *fout = fopen(outfile, "wb");
    if (!fout) { fclose(fin); return -1; }
    uint8_t in_block[16], out_block[16], next[16];
    size_t n = fread(in_block, 1, 16, fin);
    while (n == 16) {
        size_t nn = fread(next, 1, 16, fin);
        aes_decrypt_block(in_block, out_block, key, key_bits);
        if (nn == 0) {
            uint8_t pad = out_block[15];
            if (pad < 1 || pad > 16) pad = 0;
            fwrite(out_block, 1, 16 - pad, fout);
        } else {
            fwrite(out_block, 1, 16, fout);
        }
        memcpy(in_block, next, 16);
        n = nn;
    }
    fclose(fin); fclose(fout);
    return 0;
}
